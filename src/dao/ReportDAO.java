package dao;

import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import exception.AccessDeniedException;
import report.Report;

public class ReportDAO {

    // Saves a record of a generated report. Only managers may do this.
    public int logReport(Report report, int userId) throws SQLException, AccessDeniedException {
        return logReport(report, userId, null);
    }

    // Same, and also keeps the full text of the report so it can be opened again later.
    public int logReport(Report report, int userId, String content) throws SQLException, AccessDeniedException {
        String sqlRole = "SELECT role FROM User WHERE userId = ?";
        String sqlInsert = "INSERT INTO Report (generatedBy, type, dateRangeStart, dateRangeEnd, content) "
                + "VALUES (?, ?, ?, ?, ?)";

        Connection con = null;
        PreparedStatement ps = null;
        ResultSet rs = null;

        try {
            con = DBConnection.getConnection();

            // Step 1: only a WarehouseManager may generate reports
            ps = con.prepareStatement(sqlRole);
            ps.setInt(1, userId);
            rs = ps.executeQuery();
            if (!rs.next() || !rs.getString("role").equals("WarehouseManager")) {
                throw new AccessDeniedException("Only a warehouse manager can generate reports.");
            }
            rs.close();
            ps.close();

            // Step 2: save the record
            ps = con.prepareStatement(sqlInsert, Statement.RETURN_GENERATED_KEYS);
            ps.setInt(1, userId);
            ps.setString(2, report.getType());
            ps.setDate(3, Date.valueOf(report.getStartDate()));
            ps.setDate(4, Date.valueOf(report.getEndDate()));
            ps.setString(5, content);
            ps.executeUpdate();
            rs = ps.getGeneratedKeys();
            rs.next();
            return rs.getInt(1);

        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
                if (con != null) {
                    con.close();
                }
            } catch (SQLException e) {
                System.out.println("Error closing resources: " + e.getMessage());
            }
        }
    }

    // ---------------------------------------------------------------
    // Past reports (managers only)
    // ---------------------------------------------------------------

    // The list of saved reports, newest first.
    // Columns: Report, Type, From, To, Generated at, Generated by
    public ArrayList<Object[]> getSavedReports(int userId) throws SQLException, AccessDeniedException {
        String sql = "SELECT r.reportId, r.type, r.dateRangeStart, r.dateRangeEnd, r.generatedAt, u.name "
                + "FROM Report r JOIN User u ON r.generatedBy = u.userId "
                + "ORDER BY r.reportId DESC";

        ArrayList<Object[]> rows = new ArrayList<Object[]>();
        Connection con = null;
        PreparedStatement ps = null;
        ResultSet rs = null;

        try {
            con = DBConnection.getConnection();
            requireManager(con, userId);

            ps = con.prepareStatement(sql);
            rs = ps.executeQuery();
            while (rs.next()) {
                rows.add(new Object[] { rs.getInt(1), rs.getString(2), String.valueOf(rs.getDate(3)),
                        String.valueOf(rs.getDate(4)), String.valueOf(rs.getTimestamp(5)).substring(0, 16),
                        rs.getString(6) });
            }
            return rows;

        } finally {
            closeAll(rs, ps, con);
        }
    }

    // The saved text of one report, or null if it was saved before texts were kept.
    public String getReportContent(int reportId, int userId) throws SQLException, AccessDeniedException {
        String sql = "SELECT content FROM Report WHERE reportId = ?";

        Connection con = null;
        PreparedStatement ps = null;
        ResultSet rs = null;

        try {
            con = DBConnection.getConnection();
            requireManager(con, userId);

            ps = con.prepareStatement(sql);
            ps.setInt(1, reportId);
            rs = ps.executeQuery();
            if (rs.next()) {
                return rs.getString(1);
            }
            return null;

        } finally {
            closeAll(rs, ps, con);
        }
    }

    private void requireManager(Connection con, int userId) throws SQLException, AccessDeniedException {
        PreparedStatement ps = null;
        ResultSet rs = null;
        try {
            ps = con.prepareStatement("SELECT role FROM User WHERE userId = ?");
            ps.setInt(1, userId);
            rs = ps.executeQuery();
            if (!rs.next() || !rs.getString("role").equals("WarehouseManager")) {
                throw new AccessDeniedException("Only a warehouse manager can use reports.");
            }
        } finally {
            if (rs != null) {
                rs.close();
            }
            if (ps != null) {
                ps.close();
            }
        }
    }

    private void closeAll(ResultSet rs, PreparedStatement ps, Connection con) {
        try {
            if (rs != null) {
                rs.close();
            }
            if (ps != null) {
                ps.close();
            }
            if (con != null) {
                con.close();
            }
        } catch (SQLException e) {
            System.out.println("Error closing resources: " + e.getMessage());
        }
    }
}